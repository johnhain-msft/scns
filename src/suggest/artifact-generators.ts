/**
 * Artifact generators — produce real, usable file contents from approved suggestions.
 *
 * Pure functions that generate content without filesystem I/O.
 * The executor handles the actual writing.
 */

import type { Suggestion } from './types.js'

export interface ArtifactOutput {
  readonly path: string
  readonly content: string
  readonly format: 'markdown' | 'yaml' | 'json' | 'javascript' | 'shell'
  readonly overwrite: boolean
}

function slugify(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

function formatEvidence(evidence: Suggestion['evidence']): string {
  if (evidence.length === 0) return ''
  const lines = evidence.map((e) => `- **${e.source}**: ${e.detail} (weight: ${e.weight})`)
  return ['', '## Evidence', '', ...lines].join('\n')
}

function formatTags(tags: readonly string[]): string {
  if (tags.length === 0) return ''
  return ['', `> Tags: ${tags.join(', ')}`].join('\n')
}

function generatePromptArtifact(suggestion: Suggestion): ArtifactOutput {
  const lines = [
    `## ${suggestion.title}`,
    '',
    suggestion.description,
    formatTags(suggestion.tags),
    formatEvidence(suggestion.evidence),
    '',
  ]

  return {
    path: '.github/copilot-instructions.md',
    content: lines.join('\n'),
    format: 'markdown',
    overwrite: false,
  }
}

function generateExtensionArtifact(suggestion: Suggestion): ArtifactOutput {
  const slug = slugify(suggestion.title)
  const safeName = JSON.stringify(slug)
  const safeDescription = JSON.stringify(suggestion.description)
  const safeTags = JSON.stringify(suggestion.tags)

  const content = [
    `// Extension: ${slug}`,
    `// Generated by SCNS from suggestion ${suggestion.id}`,
    '',
    'module.exports = {',
    `  name: ${safeName},`,
    `  description: ${safeDescription},`,
    `  keywords: ${safeTags},`,
    '',
    '  tools: [',
    '    {',
    `      name: ${safeName},`,
    `      description: ${safeDescription},`,
    '      parameters: {',
    '        type: "object",',
    '        properties: {},',
    '      },',
    '      execute: async (args, context) => {',
    '        // TODO: Implement tool logic',
    `        return { result: "executed ${slug}" };`,
    '      },',
    '    },',
    '  ],',
    '};',
  ].join('\n')

  return {
    path: `.github/extensions/${slug}.js`,
    content,
    format: 'javascript',
    overwrite: true,
  }
}

function generateLspArtifact(_suggestion: Suggestion): ArtifactOutput {
  const config = {
    compilerOptions: {
      strict: true,
      noUncheckedIndexedAccess: true,
      noImplicitOverride: true,
      exactOptionalPropertyTypes: false,
      forceConsistentCasingInFileNames: true,
      esModuleInterop: true,
      skipLibCheck: true,
      moduleResolution: 'bundler',
      module: 'ESNext',
      target: 'ES2022',
    },
    include: ['src'],
    exclude: ['node_modules', 'dist'],
  }

  return {
    path: 'tsconfig.json',
    content: JSON.stringify(config, null, 2),
    format: 'json',
    overwrite: true,
  }
}

function generateGithubActionArtifact(suggestion: Suggestion): ArtifactOutput {
  const slug = slugify(suggestion.title)
  const safeTitle = suggestion.title.replace(/[:"'$`\\]/g, '')
  const safeDescription = suggestion.description.replace(/[:"'$`\\]/g, '')

  const content = [
    `# ${safeDescription}`,
    `name: ${safeTitle}`,
    '',
    'on:',
    '  push:',
    '    branches: [main]',
    '  pull_request:',
    '    branches: [main]',
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    '  build:',
    '    runs-on: ubuntu-latest',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '',
    '      - name: Setup Node.js',
    '        uses: actions/setup-node@v4',
    '        with:',
    "          node-version: '22'",
    '          cache: npm',
    '',
    '      - name: Install dependencies',
    '        run: npm ci',
    '',
    '      - name: Lint',
    '        run: npm run lint',
    '',
    '      - name: Type check',
    '        run: npm run typecheck',
    '',
    '      - name: Test',
    '        run: npm test',
    '',
    '      - name: Build',
    '        run: npm run build',
  ].join('\n')

  return {
    path: `.github/workflows/${slug}.yml`,
    content,
    format: 'yaml',
    overwrite: true,
  }
}

function generateAgenticWorkflowArtifact(suggestion: Suggestion): ArtifactOutput {
  const slug = slugify(suggestion.title)

  const lines = [
    `# ${suggestion.title}`,
    '',
    suggestion.description,
    '',
    '## Steps',
    '',
    '### 1. Observe',
    '',
    'Gather context from the current environment, session history, and recent changes.',
    '',
    '### 2. Decide',
    '',
    'Analyze gathered context and determine the appropriate action based on patterns.',
    '',
    '### 3. Act',
    '',
    'Execute the chosen action with appropriate guardrails and safety checks.',
    '',
    '### 4. Validate',
    '',
    'Verify the action produced the expected outcome and log results.',
    '',
    '## Configuration',
    '',
    `- **Workflow ID**: ${slug}`,
    `- **Confidence threshold**: ${suggestion.confidence}`,
    `- **Created**: ${suggestion.createdAt}`,
    formatEvidence(suggestion.evidence),
    formatTags(suggestion.tags),
    '',
  ]

  return {
    path: `.scns/workflows/${slug}.md`,
    content: lines.join('\n'),
    format: 'markdown',
    overwrite: true,
  }
}

function generateInstructionArtifact(suggestion: Suggestion): ArtifactOutput {
  const lines = [
    `## ${suggestion.title}`,
    '',
    suggestion.description,
    formatTags(suggestion.tags),
    '',
  ]

  return {
    path: 'CLAUDE.md',
    content: lines.join('\n'),
    format: 'markdown',
    overwrite: false,
  }
}

function generateSkillArtifact(suggestion: Suggestion): ArtifactOutput {
  const slug = slugify(suggestion.title)
  const safeTitle = suggestion.title.replace(/:/g, ' -')
  const safeDescription = suggestion.description.replace(/:/g, ' -')
  const tagsList = suggestion.tags.map((t) => `  - ${t}`).join('\n')

  const frontmatter = [
    '---',
    `name: ${safeTitle}`,
    `description: ${safeDescription}`,
    'tags:',
    tagsList || '  []',
    '---',
  ].join('\n')

  const body = [
    '',
    `# ${suggestion.title}`,
    '',
    suggestion.description,
    '',
    '## Usage',
    '',
    'This skill can be invoked to automate the described pattern.',
    '',
    '## When to Use',
    '',
    'Use this skill when you encounter the pattern described above.',
    formatEvidence(suggestion.evidence),
    '',
  ]

  return {
    path: `.copilot/skills/${slug}.md`,
    content: frontmatter + body.join('\n'),
    format: 'markdown',
    overwrite: true,
  }
}

/** Generate a real artifact from an approved suggestion */
export function generateArtifact(suggestion: Suggestion): ArtifactOutput | null {
  switch (suggestion.type) {
    case 'prompt':
      return generatePromptArtifact(suggestion)
    case 'extension':
      return generateExtensionArtifact(suggestion)
    case 'lsp':
      return generateLspArtifact(suggestion)
    case 'github-action':
      return generateGithubActionArtifact(suggestion)
    case 'agentic-workflow':
      return generateAgenticWorkflowArtifact(suggestion)
    case 'instruction':
      return generateInstructionArtifact(suggestion)
    case 'skill':
      return generateSkillArtifact(suggestion)
    default:
      return null
  }
}
